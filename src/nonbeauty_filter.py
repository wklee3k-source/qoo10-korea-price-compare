def is_non_beauty(keyword: str) -> bool:
    """화장품이 아니라고 판단되면 True.

    비화장품 표지가 있어도 화장품 신호어가 함께 있으면 False(=살린다).
    """
    if not keyword:
        return False
    if not _NON_BEAUTY.search(keyword):
        return False
    if _BEAUTY_SIGNAL.search(keyword):
        return False
    return True


def filter_keywords(keywords, max_drop_ratio: float = 0.35):
    """검색어 목록에서 비화장품을 뺀다.

    제거 비율이 max_drop_ratio를 넘으면 **아무것도 지우지 않고 원본을
    그대로 돌려준다.** 필터가 잘못 넓어졌을 때 큐를 통째로 날려
    워커를 완전정지시키는 사고(§4.8)를 막기 위한 안전판이다.

    반환: (남긴 검색어 목록, 제거된 검색어 목록, 안전판이 걸렸는지)
    """
    keywords = list(keywords or [])
    if not keywords:
        return [], [], False
    kept, dropped = [], []
    for kw in keywords:
        (dropped if is_non_beauty(kw) else kept).append(kw)
    if len(dropped) / len(keywords) > max_drop_ratio:
        return keywords, [], True
    return kept, dropped, False
